const fs=require('fs'),vm=require('vm'),path=require('path');
const ROOT=path.resolve(__dirname,'..');
function read(rel){return JSON.parse(fs.readFileSync(path.join(ROOT,rel),'utf8'));}
const core=read('data/skill_runtime/runtime_core_1_v1.json');
const generated=read('data/skill_runtime/runtime_generated_all.json');
const pending=read('data/skill_runtime/runtime_pending_review.json');
const ids=[5455,5456,5457,5458,5459,5460];
const profiles=Object.fromEntries(ids.map(id=>[id,core.skills[String(id)]?.runtimeProfile]));
function assert(ok,msg){if(!ok)throw new Error(msg);}
assert(core.version==='0.9.82CS','runtime core version');
assert(generated.summary.officialRuntime===824,'official runtime count');
assert(generated.summary.pending===315,'pending count');
assert(ids.every(id=>profiles[id]&&profiles[id].formula),'six profiles missing');
assert(ids.every(id=>!pending.skills.some(x=>Number(x.skillId)===id)),'completed skill remained pending');
assert(profiles[5455].initialTargeting.radius===2,'meteor initial radius');
assert(profiles[5457].statusEffects.waterDamageTakenRate===15,'misty frost water vulnerability');
assert(profiles[5459].maxTicks===10&&profiles[5459].statusEffects.allDamageTakenRate===10,'ground gravity runtime');
assert(profiles[5460].statusDuration===18000,'napalm curse duration');

const sandbox={console,window:{},Math,Date,setTimeout,clearTimeout,setInterval,clearInterval};
sandbox.window=sandbox;
sandbox.player={baseLevel:200,stats:{spl:50},equipment:{}};
sandbox.currentMonster={currentHp:999999,stats:{},element:'Neutral'};
sandbox.skillsData={runtimeProfiles:core.skills,skillIndex:{}};
sandbox.getSkillLevel=id=>(ids.includes(Number(id))||Number(id)===5450)?10:0;
sandbox.calculateDerivedPlayerStats=()=>({stats:{spl:50},matk:1});
sandbox.MultiHitResolver={normalize:(p,l)=>({damageHitCount:Number(Array.isArray(p.damageHitCount)?p.damageHitCount[l-1]:p.damageHitCount||1),visualHitCount:Number(Array.isArray(p.visualHitCount)?p.visualHitCount[l-1]:p.visualHitCount||1)})};
sandbox.CombatDamagePipeline={resolveMagicSkill:(p,l,t,o)=>({damage:Number(o.ratio)})};
sandbox.HitResolver={resolve:()=>({hit:true})};
sandbox.CriticalResolver={resolve:()=>({critical:false})};
sandbox.PerfectDodgeResolver={resolve:()=>({dodged:false})};
sandbox.clampSkillLevel=(skill,l)=>Number(l||10);
sandbox.getRuntimeHitCount=()=>1;
sandbox.getActiveBuffBonusTotals=()=>({});
sandbox.getPassiveSkillBonusTotals=()=>({});
sandbox.getEquippedWeaponTypeRuntime=()=>'';
sandbox.getLevelValue=(v,l,d)=>Array.isArray(v)?(v[l-1]??d):(v??d);
sandbox.window.MultiHitResolver=sandbox.MultiHitResolver;
sandbox.window.CombatDamagePipeline=sandbox.CombatDamagePipeline;
sandbox.window.HitResolver=sandbox.HitResolver;
sandbox.window.CriticalResolver=sandbox.CriticalResolver;
sandbox.window.PerfectDodgeResolver=sandbox.PerfectDodgeResolver;
vm.createContext(sandbox);
vm.runInContext(fs.readFileSync(path.join(ROOT,'js/skill_engine.js'),'utf8'),sandbox,{filename:'skill_engine.js'});
function ratio(id,phase='tick'){return sandbox.calculateSkillAttackDamage({id,maxLevel:10},10,sandbox.currentMonster,{skipHitCheck:true,phase});}
assert(ratio(5455,'initial')===9130,'5455 initial formula '+ratio(5455,'initial'));
assert(ratio(5455,'tick')===5400,'5455 tick formula '+ratio(5455,'tick'));
assert(ratio(5456)===40590,'5456 formula '+ratio(5456));
assert(ratio(5457,'initial')===4800,'5457 initial formula '+ratio(5457,'initial'));
assert(ratio(5457,'tick')===12980,'5457 tick formula '+ratio(5457,'tick'));
assert(ratio(5458)===24750,'5458 formula '+ratio(5458));
assert(ratio(5459,'initial')===37300,'5459 initial formula '+ratio(5459,'initial'));
assert(ratio(5459,'tick')===17820,'5459 tick formula '+ratio(5459,'tick'));
